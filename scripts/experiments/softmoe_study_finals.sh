#!/bin/bash
###############################################################################
# Soft MoE tuning study — FINALS template.
#
# Runs one screen-winning config at the FULL protocol: full ImageNet
# (train_subset_frac 1.0), 3 seeds (42 / 123 / 456), otherwise the config
# exactly as screened. Seeds are round-robin distributed across GPUS and
# launched under nohup (same conventions as softmoe_study_screen.sh).
#
# Usage (on the GPU box, from the repo root):
#   GPUS="0 1 2" bash scripts/experiments/softmoe_study_finals.sh softmoe_study_r6
#   # arg = config name in configs/vit/ (with or without .yaml), or a path
#
# Guards / logs:
#   - skip iff outputs/softmoe_study_finals/<cfg>_s<seed>/results.json exists
#   - per-run log:  outputs/softmoe_study_finals/<cfg>_s<seed>.log
#   - per-GPU log:  outputs/softmoe_study_finals/log_<cfg>_gpu<id>.txt
###############################################################################

set -u
cd "$(dirname "$0")/../.." || exit 1

if [ $# -lt 1 ]; then
    echo "Usage: GPUS=\"0 1 2\" bash $0 <config name in configs/vit/>"
    exit 1
fi

PYTHON=${PYTHON:-python}
GPUS=${GPUS:-"0"}
OUTDIR_BASE=${OUTDIR_BASE:-"./outputs/softmoe_study_finals"}
DEVICE=${DEVICE:-cuda}
if [ -n "${SEEDS_OVERRIDE:-}" ]; then SEEDS=($SEEDS_OVERRIDE); else SEEDS=(42 123 456); fi

# Resolve config argument: bare name, name.yaml, or explicit path.
ARG=$1
if [ -f "$ARG" ]; then
    CFG_PATH="$ARG"
elif [ -f "configs/vit/${ARG%.yaml}.yaml" ]; then
    CFG_PATH="configs/vit/${ARG%.yaml}.yaml"
else
    echo "ERROR: config not found: $ARG (looked at configs/vit/${ARG%.yaml}.yaml)"
    exit 1
fi
CFG_STEM=$(basename "$CFG_PATH" .yaml)

GPU_ARR=($GPUS)
NGPU=${#GPU_ARR[@]}
mkdir -p "$OUTDIR_BASE"

echo "============================================================"
echo " Soft MoE tuning-study FINALS: $CFG_STEM × seeds ${SEEDS[*]}"
echo " full data (train_subset_frac=1.0), GPUs: $GPUS"
echo " $(date)"
echo "============================================================"

# Pre-generate one full-data yaml per seed (subset keys stripped, seed +
# output_dir + experiment_name overridden; everything else untouched).
for SEED in "${SEEDS[@]}"; do
    ENAME="${CFG_STEM}_s${SEED}"
    ODIR="$OUTDIR_BASE/$ENAME"
    mkdir -p "$ODIR"
    $PYTHON - "$CFG_PATH" "$OUTDIR_BASE/_tmp_${ENAME}.yaml" "$SEED" "$ODIR" "$ENAME" <<'EOF'
import sys
import yaml

cfg_path, out_path, seed, odir, ename = sys.argv[1:6]
cfg = yaml.safe_load(open(cfg_path))
cfg['seed'] = int(seed)
cfg['experiment_name'] = ename
cfg['output_dir'] = odir
dcfg = cfg.setdefault('data', {})
dcfg['train_subset_frac'] = 1.0          # FINALS: full ImageNet train split
dcfg.pop('train_subset_seed', None)
yaml.safe_dump(cfg, open(out_path, 'w'), sort_keys=False)
print(f'  wrote {out_path} (seed={seed}, full data)')
EOF
    if [ $? -ne 0 ]; then echo "ERROR: config generation failed for seed $SEED"; exit 1; fi
done

for gi in "${!GPU_ARR[@]}"; do
    GPU=${GPU_ARR[$gi]}
    WORKER="$OUTDIR_BASE/_worker_${CFG_STEM}_gpu${GPU}.sh"
    {
        echo "#!/bin/bash"
        echo "# auto-generated by softmoe_study_finals.sh — GPU $GPU worker"
        echo "export CUDA_VISIBLE_DEVICES=$GPU"
        echo "export OPENBLAS_NUM_THREADS=8 OMP_NUM_THREADS=8 MKL_NUM_THREADS=8"
        for si in "${!SEEDS[@]}"; do
            if [ $(( si % NGPU )) -ne "$gi" ]; then continue; fi
            SEED=${SEEDS[$si]}
            ENAME="${CFG_STEM}_s${SEED}"
            cat <<EOW
if [ -f "$OUTDIR_BASE/$ENAME/results.json" ]; then
    echo "[gpu$GPU] $ENAME — DONE, skipping"
else
    echo "[gpu$GPU] $ENAME starting: \$(date)"
    $PYTHON run.py --wandb --config "$OUTDIR_BASE/_tmp_${ENAME}.yaml" --device $DEVICE \\
        2>&1 | tee "$OUTDIR_BASE/${ENAME}.log"
    echo "[gpu$GPU] $ENAME finished: \$(date)"
fi
EOW
        done
        echo "echo \"[gpu$GPU] worker done: \$(date)\""
    } > "$WORKER"
    chmod +x "$WORKER"
    if [ "${FOREGROUND:-0}" = "1" ]; then
        echo "  GPU $GPU: running worker in foreground -> $OUTDIR_BASE/log_${CFG_STEM}_gpu${GPU}.txt"
        bash "$WORKER" 2>&1 | tee "$OUTDIR_BASE/log_${CFG_STEM}_gpu${GPU}.txt"
    else
        nohup bash "$WORKER" > "$OUTDIR_BASE/log_${CFG_STEM}_gpu${GPU}.txt" 2>&1 &
        echo "  GPU $GPU: worker PID $! -> $OUTDIR_BASE/log_${CFG_STEM}_gpu${GPU}.txt"
    fi
done

echo ""
if [ "${FOREGROUND:-0}" = "1" ]; then echo "All seeds finished. Aggregate:"; else echo "All workers launched. Aggregate once done:"; fi
echo "  $PYTHON - <<'EOF'"
echo "import json, os"
echo "accs = []"
echo "for s in [${SEEDS[*]// /, }]:"
echo "    p = '$OUTDIR_BASE/${CFG_STEM}_s%d/results.json' % s"
echo "    if os.path.exists(p): accs.append(json.load(open(p))['best_top1'])"
echo "print('$CFG_STEM:', accs)"
echo "if accs:"
echo "    m = sum(accs)/len(accs)"
echo "    print('mean +/- std: %.2f +/- %.2f (n=%d)' % (m, (sum((a-m)**2 for a in accs)/len(accs))**0.5, len(accs)))"
echo "EOF"
