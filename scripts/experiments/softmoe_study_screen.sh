#!/bin/bash
###############################################################################
# Soft MoE tuning study — SCREEN (20% ImageNet subset, seed 42,
# 100 epochs). 7 arms, one run each:
#
#   r0_pivot           — deployed recipe re-based to 20% subset (pivot cell)
#   r1_lr5e4           — lr 5e-4
#   r2_lr1e4           — lr 1e-4
#   r3_e8_h192         — 8 experts × hidden 192  (coarse granularity)
#   r4_e16_h96         — 16 experts × hidden 96  (medium granularity)
#   r5_start6          — moe_start_block=6 (paper-canonical second-half, N=32 h=48)
#   r6_computematched  — compute-matched (N=32 h=1600 S=5, ~8.51 table-GMACs,
#                        481M params by design, skip_param_check)
#
# Usage (on the GPU box, from the repo root):
#   GPUS="0 1 2" bash scripts/experiments/softmoe_study_screen.sh
#
# GPUS is a space-separated GPU id list (default "0"). The 7 runs are
# round-robin distributed across the listed GPUs; each GPU runs its share
# sequentially inside a nohup'd worker, so the script returns immediately
# and survives ssh disconnect.
#
# Guards / logs:
#   - a run is skipped iff outputs/softmoe_study_screen/<r_name>/results.json
#     exists (same convention as rtx5090_* scripts)
#   - per-run log:    outputs/softmoe_study_screen/<r_name>.log
#   - per-GPU log:    outputs/softmoe_study_screen/log_gpu<id>.txt
###############################################################################

set -u
cd "$(dirname "$0")/../.." || exit 1

PYTHON=${PYTHON:-python}
GPUS=${GPUS:-"0"}
OUTDIR_BASE=${OUTDIR_BASE:-"./outputs/softmoe_study_screen"}
CFG_DIR=${CFG_DIR:-"configs/vit"}
DEVICE=${DEVICE:-cuda}

# <output_dir_name>:<config_file> — names must match the output_dir baked
# into each yaml (the yaml's output_dir is authoritative for run.py; the
# name here drives the skip guard and log naming).
RUNS=(
    "r0_pivot:softmoe_study_r0.yaml"
    "r1_lr5e4:softmoe_study_r1.yaml"
    "r2_lr1e4:softmoe_study_r2.yaml"
    "r3_e8_h192:softmoe_study_r3.yaml"
    "r4_e16_h96:softmoe_study_r4.yaml"
    "r5_start6:softmoe_study_r5.yaml"
    "r6_computematched:softmoe_study_r6.yaml"
)

GPU_ARR=($GPUS)
NGPU=${#GPU_ARR[@]}
mkdir -p "$OUTDIR_BASE"

echo "============================================================"
echo " Soft MoE tuning-study screen: ${#RUNS[@]} runs across $NGPU GPU(s): $GPUS"
echo " $(date)"
echo "============================================================"

for gi in "${!GPU_ARR[@]}"; do
    GPU=${GPU_ARR[$gi]}
    WORKER="$OUTDIR_BASE/_worker_gpu${GPU}.sh"
    {
        echo "#!/bin/bash"
        echo "# auto-generated by softmoe_study_screen.sh — GPU $GPU worker"
        echo "export CUDA_VISIBLE_DEVICES=$GPU"
        echo "export OPENBLAS_NUM_THREADS=8 OMP_NUM_THREADS=8 MKL_NUM_THREADS=8"
        for ri in "${!RUNS[@]}"; do
            if [ $(( ri % NGPU )) -ne "$gi" ]; then continue; fi
            SPEC=${RUNS[$ri]}
            NAME="${SPEC%%:*}"
            CFG="${SPEC##*:}"
            cat <<EOW
if [ -f "$OUTDIR_BASE/$NAME/results.json" ]; then
    echo "[gpu$GPU] $NAME — DONE, skipping"
else
    mkdir -p "$OUTDIR_BASE/$NAME"
    echo "[gpu$GPU] $NAME starting: \$(date)"
    $PYTHON run.py --wandb --config "$CFG_DIR/$CFG" --device $DEVICE \\
        2>&1 | tee "$OUTDIR_BASE/${NAME}.log"
    echo "[gpu$GPU] $NAME finished: \$(date)"
fi
EOW
        done
        echo "echo \"[gpu$GPU] worker done: \$(date)\""
    } > "$WORKER"
    chmod +x "$WORKER"
    nohup bash "$WORKER" > "$OUTDIR_BASE/log_gpu${GPU}.txt" 2>&1 &
    echo "  GPU $GPU: worker PID $! -> $OUTDIR_BASE/log_gpu${GPU}.txt"
done

echo ""
echo "All workers launched. Monitor with:"
echo "  tail -f $OUTDIR_BASE/log_gpu*.txt"
echo "Aggregate results once runs finish:"
echo "  $PYTHON - <<'EOF'"
echo "import json, os"
echo "for n in ['r0_pivot','r1_lr5e4','r2_lr1e4','r3_e8_h192','r4_e16_h96','r5_start6','r6_computematched']:"
echo "    p = '$OUTDIR_BASE/%s/results.json' % n"
echo "    print(n, json.load(open(p))['best_top1'] if os.path.exists(p) else 'pending')"
echo "EOF"
